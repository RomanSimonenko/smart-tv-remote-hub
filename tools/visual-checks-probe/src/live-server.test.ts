import {test,expect} from 'vitest';
import sharp from 'sharp';
import {startLiveProbe} from './live-server.js';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
test('loopback probe processes a real image boundary and rejects cross-origin frames',async()=>{
 const evidenceDirectory=await mkdtemp(join(tmpdir(),'screen-diagnostics-'));
 const {server,url}=await startLiveProbe(0,{evidenceDirectory});
 try{
  const page=await fetch(url);expect(page.status).toBe(200);
  expect(await page.text()).toContain('name="live-preview-width" content="960"');
  const image=await sharp({create:{width:640,height:480,channels:3,background:'black'}}).png().toBuffer();
  expect((await fetch(url+'/frame',{method:'POST',headers:{Origin:'https://example.invalid','Content-Type':'image/png'},body:image})).status).toBe(403);
  const response=await fetch(url+'/frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1'},body:image});
  expect(response.status).toBe(200);expect(await response.json()).toMatchObject({status:'not-found',reason:'no-qualified-candidate',candidates:[]});
  expect(await readFile(join(evidenceDirectory,'failure.png'))).toEqual(image);
  expect(JSON.parse(await readFile(join(evidenceDirectory,'failure.json'),'utf8'))).toMatchObject({diagnostics:{contours:0,accepted:0}});
  const screen=await sharp(Buffer.from('<svg width="640" height="480"><rect width="640" height="480" fill="#202020"/><rect x="100" y="100" width="440" height="250" fill="#ddd"/></svg>')).png().toBuffer();
  const unverified=await fetch(url+'/frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1'},body:screen});
  expect(await unverified.json()).toMatchObject({status:'found'});
  const dots=Array.from({length:72},(_,i)=>`<circle cx="${130+i%12*33}" cy="${130+Math.floor(i/12)*35}" r="11" fill="#eee"/>`).join('');
  const framed=await sharp(Buffer.from(`<svg width="640" height="480"><rect width="640" height="480" fill="#202020"/><rect x="94" y="94" width="452" height="262" fill="#777"/><rect x="100" y="100" width="440" height="250" fill="#203080"/>${dots}</svg>`)).png().toBuffer();
  const found=await fetch(url+'/frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1'},body:framed});
  const observation=await found.json() as {status:string;image:string;corners:unknown[]};
  expect(observation.status).toBe('found');expect(observation.corners).toHaveLength(4);
  const output=await sharp(Buffer.from(observation.image,'base64')).metadata();
  expect(output.width).toBeGreaterThan(430);expect(output.width).toBeLessThanOrEqual(441);
  const lostInner=await fetch(url+'/frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1'},body:screen});
  const lost=await lostInner.json();
  expect(lost).toMatchObject({status:'found'});
  expect(lost).toHaveProperty('image');
  const live=await fetch(url+'/live-frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1'},body:framed});
  const liveResult=await live.json() as {status:string;image:string;corners:unknown[]};
  expect(liveResult.status).toBe('found');expect((await sharp(Buffer.from(liveResult.image,'base64')).metadata()).width).toBe(960);
  const full=await sharp(framed).resize(1920,1440).png().toBuffer();
  const snapshotHeaders={Origin:url,'Content-Type':'image/png','X-Live-Probe':'1','X-Screen-Prior':JSON.stringify(liveResult.corners)};
  const snapshot=await fetch(url+'/snapshot-frame',{method:'POST',headers:snapshotHeaders,body:full});
  expect(snapshot.status).toBe(200);
  const snap=await snapshot.json() as {status:string;image:string};
  expect(snap.status).toBe('found');
  const snapMeta=await sharp(Buffer.from(snap.image,'base64')).metadata();
  expect(snapMeta.width).toBeGreaterThan(1250);expect(snapMeta.width).toBeLessThan(1340);
  const missing=await fetch(url+'/snapshot-frame',{method:'POST',headers:snapshotHeaders,body:image});
  const missingBody=await missing.json();expect(missingBody).toMatchObject({status:'not-found'});expect(missingBody).not.toHaveProperty('image');
  expect((await fetch(url+'/snapshot-frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1'},body:full})).status).toBe(422);
  const blankLive=await fetch(url+'/live-frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1','X-Screen-Prior':JSON.stringify(liveResult.corners)},body:image});
  expect(await blankLive.json()).toMatchObject({status:'not-found'});
  const badPrior=await fetch(url+'/live-frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1','X-Screen-Prior':'[[1,2]]'},body:framed});
  expect(badPrior.status).toBe(422);
  const nested=await sharp(Buffer.from('<svg width="640" height="480"><rect width="640" height="480" fill="#202020"/><rect x="80" y="70" width="480" height="310" fill="#aaa"/><rect x="110" y="100" width="420" height="250" fill="#4050dd"/></svg>')).png().toBuffer();
  const ambiguous=await fetch(url+'/frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1'},body:nested});
  const diagnostics=await ambiguous.json() as {status:string;reason:string;candidates:Array<Array<{x:number;y:number}>>};
  expect(diagnostics.status).toBe('not-found');expect(diagnostics.reason).toBe('ambiguous-candidates');
  expect(diagnostics.candidates).toHaveLength(2);
  expect(await readFile(join(evidenceDirectory,'failure.png'))).toEqual(image);
  expect(diagnostics.candidates.flat().every(p=>p.x>=0&&p.x<=1&&p.y>=0&&p.y<=1)).toBe(true);
  expect((await fetch(url+'/frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1'},body:'broken'})).status).toBe(422);
  expect((await fetch(url+'/frame',{method:'POST',headers:{Origin:url,'Content-Type':'image/png','X-Live-Probe':'1'},body:Buffer.alloc(8*1024*1024+1)})).status).toBe(413);
 }finally{await new Promise<void>((resolve,reject)=>{server.close(e=>e?reject(e):resolve());server.closeAllConnections();});await rm(evidenceDirectory,{recursive:true,force:true});}
},20000);
